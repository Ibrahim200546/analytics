create policy "profile owners and admins can read profiles" on public.profiles for select
using (id = auth.uid() or public.is_ismi_admin());
create policy "profile owners can update their profile" on public.profiles for update
using (id = auth.uid()) with check (id = auth.uid());

create policy "members can read their organizations" on public.organizations for select
using (public.can_access_organization(id));
create policy "admins manage organizations" on public.organizations for all
using (public.is_ismi_admin()) with check (public.is_ismi_admin());

create policy "members can read organization memberships" on public.organization_members for select
using (public.can_access_organization(organization_id));
create policy "admins manage organization memberships" on public.organization_members for all
using (public.is_ismi_admin()) with check (public.is_ismi_admin());

create policy "members manage accessible projects" on public.projects for all
using (public.can_access_organization(organization_id)) with check (public.can_access_organization(organization_id));
create policy "members read project articles" on public.project_articles for select
using (exists (select 1 from public.projects where projects.id = project_id and public.can_access_organization(projects.organization_id)));
create policy "members manage project article flags" on public.project_articles for all
using (exists (select 1 from public.projects where projects.id = project_id and public.can_access_organization(projects.organization_id)))
with check (exists (select 1 from public.projects where projects.id = project_id and public.can_access_organization(projects.organization_id)));
create policy "members read articles for their projects" on public.articles for select
using (exists (select 1 from public.project_articles join public.projects on projects.id = project_articles.project_id where project_articles.article_id = articles.id and public.can_access_organization(projects.organization_id)));
create policy "members manage parser accounts" on public.organization_accounts for all
using (public.can_access_organization(organization_id)) with check (public.can_access_organization(organization_id));
create policy "members read subscriptions" on public.subscriptions for select
using (public.can_access_organization(organization_id));
create policy "admins manage subscriptions" on public.subscriptions for all
using (public.is_ismi_admin()) with check (public.is_ismi_admin());
