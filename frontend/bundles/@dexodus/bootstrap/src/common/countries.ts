export const getEmojiIconForCountry = (country: Country): string => {
    const isoCode = country.split('/')[0].toUpperCase();

    const codePoints = isoCode
        .split('')
        .map(char => 127397 + char.charCodeAt(0));

    return String.fromCodePoint(...codePoints);
}

export const getCoincidencesByPhone = (phone: string): CountryPhoneFormat[] => {
    const coincidences: CountryPhoneFormat[] = [];

    for (const formatKey in CountryPhoneFormat) {
        const maskTokens = createMaskTokens(CountryPhoneFormat[formatKey as keyof typeof CountryPhoneFormat]);

        if (checkValueByMaskTokens(phone, maskTokens)) {
            coincidences.push(CountryPhoneFormat[formatKey as keyof typeof CountryPhoneFormat]);
        }
    }

    return coincidences;
}

export const getCountryByPhoneFormat = (countryPhoneFormat: CountryPhoneFormat): Country | null => {
    for (const country in Country) {
        if (CountryPhoneFormat[country as keyof typeof CountryPhoneFormat] === countryPhoneFormat) {
            return Country[country as keyof typeof Country];
        }
    }
    return null;
}

export const getCountryPhoneFormat = (country: Country): CountryPhoneFormat => {
    return CountryPhoneFormat[country as unknown as keyof typeof CountryPhoneFormat];
}

export const getCountryByISO = (iso: string): Country|null => {
    iso = iso.toUpperCase();

    for (const country in Country) {
        if (Country[country as keyof typeof Country].toUpperCase().includes(iso)) {
            return Country[country as keyof typeof Country];
        }
    }

    return null;
}
